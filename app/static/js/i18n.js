const STORAGE_KEY = "bs-language";
let current = "en";

export function getLanguage() {
  return current;
}

export function getLocale(code = current) {
  return (LANGUAGES.find((l) => l.code === code) || LANGUAGES[0]).locale;
}

/** Switch language, remember it, and update <html lang> so screen readers pronounce it right. */
export function setLanguage(code) {
  current = STRINGS[code] ? code : "en";
  document.documentElement.lang = current;
  try {
    localStorage.setItem(STORAGE_KEY, current);
  } catch {
    /* private mode / storage blocked: language just is not remembered */
  }
}

/** Language saved from an earlier visit, or null. */
export function savedLanguage() {
  try {
    const code = localStorage.getItem(STORAGE_KEY);
    return STRINGS[code] ? code : null;
  } catch {
    return null;
  }
}

/** Translate a key, filling {placeholders}. Falls back to English, then to the key itself. */
export function t(key, vars = {}) {
  const text = (STRINGS[current] && STRINGS[current][key]) || STRINGS.en[key] || key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] !== undefined ? String(vars[name]) : `{${name}}`));
}

/** For tests / review: keys missing in a language compared with English. */
export function missingKeys(code) {
  return Object.keys(STRINGS.en).filter((k) => !(STRINGS[code] || {})[k]);
}
